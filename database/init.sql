CREATE DATABASE IF NOT EXISTS user_mapping CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;

USE user_mapping;

CREATE TABLE IF NOT EXISTS user_mappings (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  id1 VARCHAR(255) NOT NULL,
  id2 VARCHAR(255) NOT NULL,
  userID CHAR(36) NOT NULL,
  createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_user_mappings_id1_id2 (id1, id2),
  UNIQUE KEY uq_user_mappings_user_id (userID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
